export const AUTH_KEY="stimulus-builder.auth";       // {access_token, refresh_token, expires_at, email}

const ALPHABET="abcdefghjkmnpqrstuvwxyz23456789";
export function newSlug(n=8,rng=Math.random){let s="";for(let i=0;i<n;i++)s+=ALPHABET[Math.floor(rng()*ALPHABET.length)];return s;}
/* The participant link is self-contained: the published id plus the project
   the data lives in (the anon key is the public client key; row-level
   security is what protects the data). A plain supabase.co project is
   carried as its ref, anything else as the full URL. */
export function projectRef(url){const m=String(url||"").match(/^https:\/\/([a-z0-9-]+)\.supabase\.co\/?$/i);return m?m[1]:String(url||"");}
export function projectUrl(sb){return /^[a-z0-9-]+$/i.test(sb)?`https://${sb}.supabase.co`:String(sb||"");}
export function participantLink(baseHref,id,project=null){
  const u=new URL(baseHref);u.search="";u.hash="";
  const q=new URLSearchParams({run:id});
  if(project&&project.url){q.set("sb",projectRef(project.url));q.set("key",project.anonKey||"");}
  return `${u.href}?${q.toString()}`;
}
/* Prolific appends these to the study URL: ?PROLIFIC_PID={{%PROLIFIC_PID%}}&STUDY_ID={{%STUDY_ID%}}&SESSION_ID={{%SESSION_ID%}} */
export function prolificParams(search){
  const p=new URLSearchParams(search);
  return {run:p.get("run")||"",sb:p.get("sb")||"",key:p.get("key")||"",
          prolific_pid:p.get("PROLIFIC_PID")||"",study_id:p.get("STUDY_ID")||"",session_id:p.get("SESSION_ID")||"",participant:p.get("participant")||""};
}
export function completionTarget(def){
  if(def.completionUrl)return def.completionUrl;
  if(def.completionCode)return `https://app.prolific.com/submissions/complete?cc=${encodeURIComponent(def.completionCode)}`;
  return "";
}
/* flatten fetched sessions (with embedded trials) into result rows */
export function sessionsToRows(sessions){
  const rows=[];
  (sessions||[]).forEach(s=>{
    const trials=[...(s.trials||[])].sort((a,b)=>a.trial-b.trial);
    trials.forEach(t=>rows.push({...t.row,session_id:s.id,session_started:s.created_at,session_completed:s.completed?1:0,
      prolific_pid:s.participant?.prolific_pid||"",study_id:s.participant?.study_id||"",prolific_session_id:s.participant?.session_id||""}));
  });
  return rows;
}
