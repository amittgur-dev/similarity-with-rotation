export class OnlineError extends Error{constructor(msg,status,body){super(msg);this.status=status;this.body=body;}}

export function makeClient({url,anonKey,fetch=globalThis.fetch,getToken=()=>null}){
  const base=String(url||"").replace(/\/+$/,"");
  async function call(path,{method="GET",body,headers={},auth=true}={}){
    const h={"apikey":anonKey,"Content-Type":"application/json",...headers};
    const token=auth?getToken():null;
    h["Authorization"]=`Bearer ${token||anonKey}`;
    const r=await fetch(base+path,{method,headers:h,body:body!==undefined?JSON.stringify(body):undefined});
    const text=await r.text();
    let data=null;try{data=text?JSON.parse(text):null;}catch{data=text;}
    if(!r.ok){
      const msg=(data&&(data.msg||data.message||data.error_description||data.error||data.hint))||`${r.status} ${r.statusText||""}`.trim();
      throw new OnlineError(msg,r.status,data);
    }
    return data;
  }
  return {
    base,
    /* ---- experimenter auth (email + password) ---- */
    signIn:(email,password)=>call("/auth/v1/token?grant_type=password",{method:"POST",body:{email,password},auth:false}),
    refresh:(refresh_token)=>call("/auth/v1/token?grant_type=refresh_token",{method:"POST",body:{refresh_token},auth:false}),
    /* ---- publishing ---- */
    publish:(rec)=>call("/rest/v1/published_experiments",{method:"POST",body:rec,headers:{Prefer:"return=representation"}}).then(r=>Array.isArray(r)?r[0]:r),
    listPublished:()=>call("/rest/v1/published_experiments?select=id,name,canvas,created_at,active,experiment_code&order=created_at.desc"),
    setActive:(id,active)=>call(`/rest/v1/published_experiments?id=eq.${encodeURIComponent(id)}`,{method:"PATCH",body:{active},headers:{Prefer:"return=minimal"}}),
    /* ---- participants (anon) ---- */
    fetchDefinition:async id=>{
      const r=await call(`/rest/v1/published_experiments?id=eq.${encodeURIComponent(id)}&select=id,definition,active&limit=1`,{auth:false});
      return Array.isArray(r)&&r[0]?r[0]:null;
    },
    /* the id is generated by the caller: participants may insert but never read sessions, so nothing can be returned */
    createSession:(rec)=>call("/rest/v1/sessions",{method:"POST",body:rec,headers:{Prefer:"return=minimal"},auth:false}).then(()=>rec),
    postTrial:(session_id,trial,row)=>call("/rest/v1/trials",{method:"POST",body:{session_id,trial,row},headers:{Prefer:"return=minimal"},auth:false}),
    completeSession:(sid)=>call("/rest/v1/rpc/complete_session",{method:"POST",body:{sid},auth:false}),
    /* ---- results (experimenter) ---- */
    fetchSessions:(experiment_id)=>call(`/rest/v1/sessions?experiment_id=eq.${encodeURIComponent(experiment_id)}&select=id,created_at,participant,calibration,completed,completed_at,trials(trial,row)&order=created_at.asc`),
  };
}
